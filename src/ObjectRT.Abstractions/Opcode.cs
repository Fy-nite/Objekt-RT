namespace ObjectRT.Abstractions;

/// <summary>ObjectRT bytecode opcodes.
/// Table 0 (0x00-0x34) are single-byte in the bytecode stream.
/// Extension tables use 0xFF prefix bytes: 0xFF 0xNN = table 1,
/// 0xFF 0xFF 0xNN = table 2, etc. The flat value is table*256 + opcode.
/// </summary>
public enum Opcode : ushort
{
    Nop       = 0x00,
    Ldc       = 0x01,
    Ldstr     = 0x02,
    Ldarg     = 0x03,
    Starg     = 0x04,
    Ldloc     = 0x05,
    Stloc     = 0x06,
    Add       = 0x07,
    Sub       = 0x08,
    Mul       = 0x09,
    Div       = 0x0A,
    Rem       = 0x0B,
    Neg       = 0x0C,
    Ceq       = 0x0D,
    Cne       = 0x0E,
    Ldfld     = 0x0F,
    Ldsfld    = 0x10,
    Stsfld    = 0x11,
    Newobj    = 0x12,
    Newarr    = 0x13,
    Ldelem    = 0x14,
    Stelem    = 0x15,
    Call      = 0x16,
    Callvirt  = 0x17,
    Ret       = 0x18,
    If        = 0x19,
    While     = 0x1A,
    Break     = 0x1B,
    Continue  = 0x1C,
    Try       = 0x1D,
    Throw     = 0x1E,
    Conv      = 0x1F,
    Castclass = 0x20,
    Isinst    = 0x21,
    Dup       = 0x22,
    Pop       = 0x23,
    Ldnull    = 0x24,
    Not       = 0x25,
    Cgt       = 0x26,
    Cge       = 0x27,
    Clt       = 0x28,
    Cle       = 0x29,
    Stfld     = 0x2A,
    LdcI4     = 0x2B,
    LdcI8     = 0x2C,
    LdcR4     = 0x2D,
    LdcR8     = 0x2E,
    And       = 0x2F,
    Xor       = 0x30,
    Or        = 0x31,
    Br        = 0x32,
    Brtrue    = 0x33,
    Brfalse   = 0x34,
    NativeCall = 0x35,
}

